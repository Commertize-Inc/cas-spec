import { MANDATE_DOMAIN_NAME, MANDATE_DOMAIN_VERSION, MANDATE_TYPE, type Mandate } from "../src/mandate.ts";
import { addressOf, G, HALF_N, mul, N, powMod } from "../src/secp256k1.ts";
import { KINDS, REVOKE_REASONS, SELECTORS, STATUSES, type Provider, type Snapshot } from "../src/credential.ts";

// The byte source for keys, nonces and hashes. Default: the OS random source (fresh every run).
// withSeed() swaps in a deterministic keccak-256 counter stream so the committed vector file can be
// regenerated byte for byte. Keys derived from a public seed are public by construction: they are
// test keys only and must never hold anything.
let source: (n: number) => Uint8Array = (n) => randomBytes(n);
const bytes32 = (): Uint8Array => source(32);

/** Runs fn with a deterministic byte stream derived from seed, then restores the random source. */
export function withSeed<T>(seed: string, fn: () => T): T {
	const prefix = new TextEncoder().encode(seed);
	let counter = 0;
	const prev = source;
	source = (n) => {
		if (n !== 32) throw new Error("seeded source serves 32-byte blocks only");
		const input = new Uint8Array(prefix.length + 4);
		input.set(prefix, 0);
		new DataView(input.buffer).setUint32(prefix.length, counter++);
		return keccak256(input);
	};
	try {
		return fn();
	} finally {
		source = prev;
	}
}

export interface Key {
	priv: bigint;
	address: Hex;
}

/** A fresh key from the current byte source. Never funded, never stored. */
export function throwawayKey(): Key {
	for (;;) {
		const d = bytesToBig(bytes32());
		if (d > 0n && d < N) return { priv: d, address: toChecksumAddress(addressOf(mul(G, d))) };
	}
}

/** ECDSA over a 32-byte digest with a nonce from the current byte source; low-s; v in {27, 28}. */
export function signDigest(digest: Uint8Array, key: Key): Hex {
	const e = bytesToBig(digest) % N;
	for (;;) {
		const k = bytesToBig(bytes32());
		if (k <= 0n || k >= N) continue;
		const R = mul(G, k)!;
		const r = R.x % N;
		if (r === 0n) continue;
		let s = (powMod(k, N - 2n, N) * ((e + r * key.priv) % N)) % N;
		if (s === 0n) continue;
		let v = Number(R.y & 1n);
		if (R.x >= N) v += 2; // never happens in practice; kept so a bad case fails loudly
		if (s > HALF_N) {
			s = N - s;
			v ^= 1;
		}
		if (v > 1) continue;
		const sig = new Uint8Array(65);
		sig.set(bigToBytes32(r), 0);
		sig.set(bigToBytes32(s), 32);
		sig[64] = 27 + v;
		return bytesToHex(sig);
	}
}

/** Turns a valid signature into its high-s twin (same signer, malleable form). */
export function highS(sig: Hex): Hex {
	const b = hexToBytes(sig);
	const s = bytesToBig(b.slice(32, 64));
	b.set(bigToBytes32(N - s), 32);
	b[64] = b[64] === 27 ? 28 : 27;
	return bytesToHex(b);
}

export function mandateTypedData(chainId: number, contract: string, message: Mandate): TypedData {
	return {
		types: {
			EIP712Domain: [
				{ name: "name", type: "string" },
				{ name: "version", type: "string" },
				{ name: "chainId", type: "uint256" },
				{ name: "verifyingContract", type: "address" },
			],
			Mandate: MANDATE_TYPE.map((f) => ({ ...f })),
		},
		primaryType: "Mandate",
		domain: { name: MANDATE_DOMAIN_NAME, version: MANDATE_DOMAIN_VERSION, chainId, verifyingContract: contract },
		message: message as unknown as Record<string, unknown>,
	};
}

export const signTyped = (td: TypedData, key: Key): Hex => signDigest(typedDataDigest(td), key);

const word = (v: bigint): string => bytesToHex(bigToBytes32(v)).slice(2);
const addrWord = (a: string): bigint => BigInt(a);

/**
 * A fake EIP-1193 provider over a snapshot, answering eth_call the way a CASCredential contract would
 * (isValid = !paused && status == ISSUED). `override` lets a test return lying or broken responses.
 */
export function fakeProvider(s: Snapshot, override: Partial<Record<"chainId" | "code" | "credential" | "paused" | "isValid" | "status" | "block", unknown>> = {}, calls: string[] = []): Provider {
	return {
		async request({ method, params }) {
			calls.push(method);
			const has = (k: string) => Object.hasOwn(override, k);
			if (method === "eth_chainId") return has("chainId") ? override.chainId : `0x${s.chainId.toString(16)}`;
			if (method === "eth_blockNumber") return has("block") ? override.block : `0x${s.blockNumber.toString(16)}`;
			if (method === "eth_getCode") {
				if (has("code")) return override.code;
				return String(params?.[0]).toLowerCase() === s.contract.toLowerCase() ? "0x6080" : "0x";
			}
			if (method !== "eth_call") throw new Error(`unexpected method ${method}`);
			const { to, data } = params![0] as { to: string; data: string };
			if (to.toLowerCase() !== s.contract.toLowerCase()) return "0x";
			const sel = data.slice(0, 10);
			const id = data.length > 10 ? BigInt(`0x${data.slice(10)}`).toString() : "";
			const c = s.credentials[id];
			const status = c ? STATUSES.indexOf(c.status) : 0;
			if (sel === SELECTORS.paused) return has("paused") ? override.paused : `0x${word(s.paused ? 1n : 0n)}`;
			if (sel === SELECTORS.status) return has("status") ? override.status : `0x${word(BigInt(status))}`;
			if (sel === SELECTORS.isValid) return has("isValid") ? override.isValid : `0x${word(!s.paused && c?.status === "ISSUED" && c?.kind !== "STATUS_REVOKED" && c?.kind !== "STATUS_REINSTATED" ? 1n : 0n)}`;
			if (sel === SELECTORS.credential) {
				if (has("credential")) return override.credential;
				if (!c) return `0x${word(0n).repeat(8)}`;
				return `0x${[
					word(addrWord(c.subject)),
					word(BigInt(KINDS.indexOf(c.kind))),
					word(BigInt(status)),
					word(BigInt(REVOKE_REASONS.indexOf(c.reason))),
					word(BigInt(c.issuedAt)),
					word(addrWord(c.issuer)),
					c.ref.slice(2).toLowerCase(),
					c.contentHash.slice(2).toLowerCase(),
				].join("")}`;
			}
			throw new Error(`unknown selector ${sel}`);
		},
	};
}

export const randomHash = (): Hex => bytesToHex(bytes32());
